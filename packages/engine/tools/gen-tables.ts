// Generates src/tables.generated.ts and src/tables.checksum.ts from DEFAULT_CONFIG.
// Run: pnpm gen:tables

import { writeFileSync } from "node:fs";
import { DEFAULT_CONFIG, regimeParams } from "../src/config.ts";
import { asciiBytes, sha256, toHex } from "../src/sha256.ts";
import { buildTable, tableLine } from "./table-builder.ts";

const params = regimeParams(DEFAULT_CONFIG);
const lines = params.map((p, i) => tableLine(i, p.H, p.sigmaPpb, buildTable(p.H, Number(p.sigmaPpb) / 1e9)));
const checksum = toHex(sha256(asciiBytes(lines.join("\n"))));

const header = "// GENERATED by tools/gen-tables.ts. Do not edit by hand.\n";
writeFileSync(
  new URL("../src/tables.generated.ts", import.meta.url),
  `${header}// One line per regime: index:H:sigmaPpb:g[0],...,g[1023]\nexport const TABLE_LINES: readonly string[] = [\n${lines.map((l) => `  "${l}",`).join("\n")}\n];\n`,
);
writeFileSync(
  new URL("../src/tables.checksum.ts", import.meta.url),
  `${header}export const TABLES_SHA256 = "${checksum}";\n`,
);
console.log(`wrote ${lines.length} tables, sha256 ${checksum}`);
