// Strategy simulator CLI (math spec 7).
//   pnpm sim --bets 5000000 [--threads 10] [--seed <64 hex>] [--report docs/reports/m1-rtp.md]

import { mkdirSync, writeFileSync } from "node:fs";
import { availableParallelism } from "node:os";
import { dirname } from "node:path";
import { Worker } from "node:worker_threads";
import { DEFAULT_CONFIG, PROFILE_NAMES, TABLES_SHA256 } from "@ape/engine";
import { PROFILES, RANDOM_ENTRY_SPAN, RISK_STRATEGIES, STAKE, STAT_FIELDS, STRATEGIES } from "./core.ts";
import type { ChunkResult } from "./core.ts";

function arg(name: string, fallback: string): string {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 && process.argv[i + 1] !== undefined ? process.argv[i + 1]! : fallback;
}

const MIN_BETS = Number(arg("bets", "5000000"));
const THREADS = Number(arg("threads", String(Math.max(1, availableParallelism() - 2))));
const SEED = arg("seed", "a9e0a9e000000000000000000000000000000000000000000000000000000001");
const REPORT = arg("report", "");
const MAX_SE = 0.005;
// Fixed chunking, so results do not depend on the thread count.
const CHUNK_ROUNDS = 5_000;
const WAVE_CHUNKS = 24;
const MAX_WAVES = Number(arg("max-waves", "400"));

const config = DEFAULT_CONFIG;
const TARGET = 1 - Number(config.entryFeeBps) / 10_000;
const S = STRATEGIES.length;
const R = RISK_STRATEGIES.length;
const maxTicks = config.maxTicks;

const stats = new Float64Array(S * PROFILES * STAT_FIELDS);
const lifeHist = new Float64Array(PROFILES * (maxTicks + 1));
const roundHist = new Float64Array(maxTicks + 1);
const graduated = new Float64Array(PROFILES);
const settled = new Float64Array(PROFILES);
const coins = new Float64Array(PROFILES);
const houseChunks: Float32Array[] = [];
let totalTicks = 0;
let totalRounds = 0;

function merge(r: ChunkResult, chunk: number): void {
  for (let i = 0; i < stats.length; i++) stats[i]! += r.stats[i]!;
  for (let i = 0; i < lifeHist.length; i++) lifeHist[i]! += r.lifeHist[i]!;
  for (let i = 0; i < roundHist.length; i++) roundHist[i]! += r.roundHist[i]!;
  for (let p = 0; p < PROFILES; p++) {
    graduated[p]! += r.graduated[p]!;
    settled[p]! += r.settled[p]!;
    coins[p]! += r.coins[p]!;
  }
  houseChunks[chunk] = r.housePerRound;
  totalTicks += r.ticks;
  totalRounds += CHUNK_ROUNDS;
}

interface Row {
  n: number;
  rtp: number;
  se: number;
  rtpUncapped: number;
  seUncapped: number;
  capShare: number;
}

/** profile = -1 for all profiles together */
function row(s: number, profile: number): Row {
  let n = 0, sum = 0, sq = 0, sumU = 0, sqU = 0, caps = 0;
  for (let p = 0; p < PROFILES; p++) {
    if (profile >= 0 && p !== profile) continue;
    const o = (s * PROFILES + p) * STAT_FIELDS;
    n += stats[o]!;
    sum += stats[o + 1]!;
    sq += stats[o + 2]!;
    sumU += stats[o + 3]!;
    sqU += stats[o + 4]!;
    caps += stats[o + 5]!;
  }
  const rtp = sum / n;
  const rtpUncapped = sumU / n;
  return {
    n,
    rtp,
    se: Math.sqrt(Math.max(0, sq / n - rtp * rtp) / n),
    rtpUncapped,
    seUncapped: Math.sqrt(Math.max(0, sqU / n - rtpUncapped * rtpUncapped) / n),
    capShare: caps / n,
  };
}

/** Pass criteria of math spec 7. */
function verdict(r: Row): string {
  if (r.rtp - 3 * r.se > TARGET) return "FAIL (above target)";
  if (Math.abs(r.rtp - TARGET) <= 3 * r.se) return "PASS";
  // Below target: allowed only when the payout cap explains the gap, i.e. the
  // same bets paid without the cap are back within tolerance.
  if (r.capShare > 0 && Math.abs(r.rtpUncapped - TARGET) <= 3 * r.seUncapped) return "PASS (cap)";
  return "FAIL (below target)";
}

const pct = (x: number, digits = 2): string => `${(x * 100).toFixed(digits)}%`;

function quantile(hist: Float64Array, offset: number, length: number, q: number): number {
  let total = 0;
  for (let i = 0; i < length; i++) total += hist[offset + i]!;
  let acc = 0;
  for (let i = 0; i < length; i++) {
    acc += hist[offset + i]!;
    if (acc >= q * total) return i;
  }
  return length - 1;
}

function histMean(hist: Float64Array, offset: number, length: number): number {
  let total = 0, sum = 0;
  for (let i = 0; i < length; i++) {
    total += hist[offset + i]!;
    sum += hist[offset + i]! * i;
  }
  return sum / total;
}

function buildReport(elapsedSec: number, converged: boolean): { text: string; pass: boolean } {
  const lines: string[] = [];
  let pass = converged;
  const secs = (ticks: number): string => `${(ticks / config.ticksPerSecond).toFixed(0)} s`;

  lines.push("# M1 — RTP report", "");
  lines.push("Generated by `pnpm sim`. Do not edit by hand.", "");
  lines.push(`- Engine tables SHA-256: \`${TABLES_SHA256}\``);
  lines.push(`- Base seed: \`${SEED}\``);
  lines.push(`- Rounds: ${totalRounds.toLocaleString("en-US")} (${(totalRounds * config.coinsPerRound).toLocaleString("en-US")} coins, ${totalTicks.toLocaleString("en-US")} ticks)`);
  lines.push(`- Minimum bets per strategy: ${MIN_BETS.toLocaleString("en-US")}; run continued until every strategy had SE <= ${pct(MAX_SE, 1)}${converged ? "" : " — **NOT REACHED, run stopped at the wave limit**"}`);
  lines.push(`- Stake per bet: ${(Number(STAKE) / 100).toFixed(2)} play coins. Entry fee ${pct(1 - TARGET, 1)}, target RTP ${pct(TARGET, 1)}, payout cap ${config.maxPayoutMult}x`);
  lines.push(`- Mid-round entry: one buy at a uniformly random tick in 1..${RANDOM_ENTRY_SPAN} (no bet if the coin is already dead)`);
  lines.push(`- Wall time: ${elapsedSec.toFixed(0)} s on ${THREADS} threads`, "");

  lines.push("## Strategies, all profiles mixed", "");
  lines.push("Pass rule (math spec §7): `|RTP - 97%| <= 3 SE`; a result below that is accepted only as `PASS (cap)`, when the same bets valued without the payout cap are back within 3 SE. Any `RTP - 3 SE > 97%` fails.", "");
  lines.push("| Strategy | Bets | RTP | SE | Cap hits | RTP without cap | SE | Result |");
  lines.push("| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |");
  for (let s = 0; s < S; s++) {
    const r = row(s, -1);
    const v = verdict(r);
    if (v.startsWith("FAIL")) pass = false;
    lines.push(`| ${STRATEGIES[s]!.name} | ${r.n.toLocaleString("en-US")} | ${pct(r.rtp, 3)} | ${pct(r.se, 3)} | ${pct(r.capShare, 3)} | ${pct(r.rtpUncapped, 3)} | ${pct(r.seUncapped, 3)} | ${v} |`);
  }

  lines.push("", "## Per profile", "");
  lines.push("RTP ± SE and result for each profile separately.", "");
  lines.push(`| Strategy | ${PROFILE_NAMES.join(" | ")} |`);
  lines.push(`| --- | ${PROFILE_NAMES.map(() => "---").join(" | ")} |`);
  let profileFails = 0;
  for (let s = 0; s < S; s++) {
    const cells = PROFILE_NAMES.map((_, p) => {
      const r = row(s, p);
      const v = verdict(r);
      if (v.startsWith("FAIL")) profileFails++;
      return `${pct(r.rtp, 2)} ± ${pct(r.se, 2)} ${v}`;
    });
    lines.push(`| ${STRATEGIES[s]!.name} | ${cells.join(" | ")} |`);
  }
  if (profileFails > 0) pass = false;

  lines.push("", "## Coin and round statistics", "");
  lines.push("| Profile | Coins | Mean life | Median life | 99th pct life | Graduated (10x) | Settled at max length |");
  lines.push("| --- | ---: | ---: | ---: | ---: | ---: | ---: |");
  for (let p = 0; p < PROFILES; p++) {
    const off = p * (maxTicks + 1);
    lines.push(
      `| ${PROFILE_NAMES[p]} | ${coins[p]!.toLocaleString("en-US")} | ${secs(histMean(lifeHist, off, maxTicks + 1))} | ${secs(quantile(lifeHist, off, maxTicks + 1, 0.5))} | ${secs(quantile(lifeHist, off, maxTicks + 1, 0.99))} | ${pct(graduated[p]! / coins[p]!, 3)} | ${pct(settled[p]! / coins[p]!, 4)} |`,
    );
  }
  lines.push("");
  lines.push(`Round length (until the last of the three coins ends): mean ${secs(histMean(roundHist, 0, maxTicks + 1))}, median ${secs(quantile(roundHist, 0, maxTicks + 1, 0.5))}, 90th pct ${secs(quantile(roundHist, 0, maxTicks + 1, 0.9))}, 99th pct ${secs(quantile(roundHist, 0, maxTicks + 1, 0.99))}.`);

  lines.push("", "## House risk", "");
  lines.push(`One player betting the maximum stake (${(Number(config.maxStake) / 100).toLocaleString("en-US")} play coins) on each of the three coins every round, same strategy all the time. Worst 1,000 consecutive rounds for the house:`, "");
  lines.push("| Strategy | House result per round (mean) | Worst 1,000-round window | In play coins |");
  lines.push("| --- | ---: | ---: | ---: |");
  const maxStake = Number(config.maxStake) / 100;
  for (let k = 0; k < R; k++) {
    let window = 0, worst = Infinity, total = 0, count = 0;
    const ring = new Float64Array(1000);
    for (const chunk of houseChunks) {
      for (let i = k; i < chunk.length; i += R) {
        const v = chunk[i]!;
        window += v - ring[count % 1000]!;
        ring[count % 1000] = v;
        total += v;
        count++;
        if (count >= 1000 && window < worst) worst = window;
      }
    }
    lines.push(`| ${RISK_STRATEGIES[k]} | ${(total / count).toFixed(4)} stakes | ${worst.toFixed(1)} stakes | ${(worst * maxStake).toLocaleString("en-US", { maximumFractionDigits: 0 })} |`);
  }
  lines.push("", "Negative numbers are house losses. This is a variance figure for sizing limits, not a fairness result.");

  lines.push("", `## Overall: ${pass ? "PASS" : "FAIL"}`, "");
  return { text: lines.join("\n"), pass };
}

function needsMore(): boolean {
  for (let s = 0; s < S; s++) {
    const r = row(s, -1);
    if (r.n < MIN_BETS || r.se > MAX_SE) return true;
  }
  return false;
}

async function main(): Promise<void> {
  const started = Date.now();
  const workers = Array.from({ length: THREADS }, () => new Worker(new URL("./worker.ts", import.meta.url)));
  let nextChunk = 0;
  let converged = false;

  const runWave = (): Promise<void> =>
    new Promise((resolve, reject) => {
      const from = nextChunk;
      const to = from + WAVE_CHUNKS;
      nextChunk = to;
      let cursor = from;
      let done = 0;
      const results = new Map<number, ChunkResult>();
      const feed = (w: Worker): void => {
        if (cursor >= to) return;
        const id = cursor++;
        w.postMessage({ id, seed: SEED, first: id * CHUNK_ROUNDS, rounds: CHUNK_ROUNDS });
      };
      for (const w of workers) {
        w.removeAllListeners("message");
        w.removeAllListeners("error");
        w.on("error", reject);
        w.on("message", (m: { id: number; result: ChunkResult }) => {
          results.set(m.id, m.result);
          done++;
          if (done === WAVE_CHUNKS) {
            for (let id = from; id < to; id++) merge(results.get(id)!, id);
            resolve();
          } else feed(w);
        });
        feed(w);
      }
    });

  for (let wave = 1; wave <= MAX_WAVES; wave++) {
    await runWave();
    let minBets = Infinity, maxSe = 0;
    for (let s = 0; s < S; s++) {
      const r = row(s, -1);
      if (r.n < minBets) minBets = r.n;
      if (r.se > maxSe) maxSe = r.se;
    }
    const elapsed = (Date.now() - started) / 1000;
    console.log(`wave ${wave}: ${totalRounds.toLocaleString("en-US")} rounds, min bets ${minBets.toLocaleString("en-US")}, max SE ${pct(maxSe, 3)}, ${(totalTicks / elapsed / 1e6).toFixed(2)}M ticks/s, ${elapsed.toFixed(0)} s`);
    if (!needsMore()) {
      converged = true;
      break;
    }
  }
  await Promise.all(workers.map((w) => w.terminate()));

  const { text, pass } = buildReport((Date.now() - started) / 1000, converged);
  console.log(`\n${text}`);
  if (REPORT !== "") {
    mkdirSync(dirname(REPORT), { recursive: true });
    writeFileSync(REPORT, `${text}\n`);
    console.log(`report written to ${REPORT}`);
  }
  process.exitCode = pass ? 0 : 1;
}

void main();
